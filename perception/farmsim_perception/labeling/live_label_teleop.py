"""
live_label_teleop.py

Interactive debug tool for the row-center label mechanism: shows the live
front_camera feed with the marked row centerline(s) projected onto it
(same forward-projection math as label_row_center.py -- world point ->
camera-local frame via /odom's live orientation + the camera's known mount
offset -> optical frame -> pinhole projection using live camera_info
intrinsics), drawn fresh into an OpenCV window every frame instead of only
saved to disk. The same window reads keyboard input to drive the robot, so
you can manually park it anywhere along a row and immediately see whether
the projected line still tracks the visible soil furrow, instead of
waiting on row_follower to drive there or digging through saved frames.

Controls (the OpenCV window must have keyboard focus -- click it first):
  w        drive straight forward
  s        drive straight backward
  a        forward + curve left
  d        forward + curve right
  space/k  stop
  q        quit this node (Ctrl+C in the terminal also works)

Publishes geometry_msgs/Twist on /cmd_vel, same as row_follower -- do NOT
run this at the same time as row_follower (follow:=true); both publish to
/cmd_vel and will fight over it.

Usage (with farm_sim.launch.py already running, follow:=false):
  ros2 run farmsim_perception live_label_teleop --ros-args \
      -p rows_file:=/path/to/rows_centerline.yaml
or automatically via:
  ros2 launch farmsim_farm farm_sim.launch.py \
      teleop_view:=true follow:=false rows_file:=/path/to/rows_centerline.yaml
"""

import math

import cv2
import message_filters
import numpy as np
import rclpy
import yaml
from cv_bridge import CvBridge
from geometry_msgs.msg import Twist
from nav_msgs.msg import Odometry
from rclpy.node import Node
from sensor_msgs.msg import CameraInfo, Image

from farmsim_farm.row_geometry import load_rows

WINDOW = 'Thorvald - camera + row label  [w/a/s/d drive, space/k stop, q quit]'


def _quat_to_matrix(x, y, z, w):
    return np.array([
        [1 - 2 * (y * y + z * z), 2 * (x * y - w * z), 2 * (x * z + w * y)],
        [2 * (x * y + w * z), 1 - 2 * (x * x + z * z), 2 * (y * z - w * x)],
        [2 * (x * z - w * y), 2 * (y * z + w * x), 1 - 2 * (x * x + y * y)],
    ])


def _pitch_matrix(pitch):
    c, s = math.cos(pitch), math.sin(pitch)
    return np.array([[c, 0.0, s], [0.0, 1.0, 0.0], [-s, 0.0, c]])


def _resample_polyline(points, spacing):
    pts = np.array(points, dtype=float)
    seg = np.diff(pts, axis=0)
    seg_len = np.linalg.norm(seg, axis=1)
    total = float(seg_len.sum())
    if total < 1e-6:
        return [pts[0]]
    n = max(2, int(total // spacing) + 1)
    targets = np.linspace(0.0, total, n)
    cum = np.concatenate([[0.0], np.cumsum(seg_len)])
    out = []
    for t in targets:
        idx = min(max(np.searchsorted(cum, t) - 1, 0), len(seg_len) - 1)
        local_t = (t - cum[idx]) / seg_len[idx] if seg_len[idx] > 1e-9 else 0.0
        out.append(pts[idx] + local_t * seg[idx])
    return out


class LiveLabelTeleop(Node):

    def __init__(self):
        super().__init__('live_label_teleop')
        self.declare_parameter('rows_file', '')
        # Must match whatever farm_sim.launch.py's camera_height/camera_pitch
        # were for this run (see gz_camera.xacro) -- these defaults match
        # farm_sim.launch.py's own defaults.
        self.declare_parameter('camera_height', 0.90)
        self.declare_parameter('camera_pitch', 0.15)
        self.declare_parameter('camera_x_offset', 0.80)
        self.declare_parameter('ground_plane_z', -0.8475)
        # Path to the topdown_<tag>.yaml capture_topdown.py wrote for this
        # SAME map's rows_file -- when set, its ground_plane_z overrides the
        # parameter above. rows_file's own (x,y) points were generated by
        # segment_rows.py/mark_rows.py using THAT file's ground_plane_z (see
        # mark_rows.pixel_to_world), so re-projecting those points back into
        # a live camera view with any other assumed elevation reintroduces
        # exactly the error the flat-plane approximation was accepted for in
        # the first place -- worse, a DIFFERENT one on each side, rather
        # than one consistent approximation. Concretely: the ground_plane_z
        # parameter default above (-0.8475) is 20250624's mean elevation;
        # silently reusing it while driving on 20250425 (whose own mean is
        # ~-0.53) was confirmed to make the projected row visibly drift
        # off the real furrow as the robot moves through terrain the fixed
        # value doesn't match.
        self.declare_parameter('topdown_meta_file', '')
        self.declare_parameter('resample_spacing', 2.0)
        self.declare_parameter('linear_speed', 0.4)
        self.declare_parameter('angular_speed', 0.4)

        rows_file = self.get_parameter('rows_file').get_parameter_value().string_value
        if not rows_file:
            self.get_logger().fatal('Parameter rows_file is required but not set')
            raise RuntimeError('rows_file parameter missing')

        spacing = self.get_parameter('resample_spacing').get_parameter_value().double_value
        self._rows = [_resample_polyline(row, spacing) for row in load_rows(rows_file)]
        if not self._rows:
            self.get_logger().fatal(f'No usable rows loaded from {rows_file}')
            raise RuntimeError('rows_file has no usable rows')

        self._ground_z = self.get_parameter('ground_plane_z').get_parameter_value().double_value
        meta_file = self.get_parameter('topdown_meta_file').get_parameter_value().string_value
        if meta_file:
            with open(meta_file, 'r') as f:
                meta = yaml.safe_load(f)
            self._ground_z = float(meta['ground_plane_z'])
            self.get_logger().info(
                f'ground_plane_z overridden from {meta_file}: {self._ground_z}')
        self._cam_h = self.get_parameter('camera_height').get_parameter_value().double_value
        self._cam_pitch = self.get_parameter('camera_pitch').get_parameter_value().double_value
        self._cam_x = self.get_parameter('camera_x_offset').get_parameter_value().double_value
        self._lin = self.get_parameter('linear_speed').get_parameter_value().double_value
        self._ang = self.get_parameter('angular_speed').get_parameter_value().double_value

        self._bridge = CvBridge()
        self._intrinsics = None
        self._cmd = Twist()
        self._last_key_label = 'stopped'

        self._cmd_pub = self.create_publisher(Twist, '/cmd_vel', 10)
        self.create_subscription(CameraInfo, '/front_camera/camera_info', self._info_cb, 10)

        # See label_row_center.py: /odom and /front_camera are independent
        # freely-running publishers, so pairing "whatever odom last arrived"
        # with each image can be tens of ms stale relative to the image's
        # own capture time -- enough to visibly jitter the projected line
        # during a bump/bounce. Sync on header stamp instead.
        odom_sub = message_filters.Subscriber(self, Odometry, '/odom')
        image_sub = message_filters.Subscriber(self, Image, '/front_camera')
        self._sync = message_filters.ApproximateTimeSynchronizer(
            [odom_sub, image_sub], queue_size=30, slop=0.06)
        self._sync.registerCallback(self._synced_cb)

        # Republish the held command continuously (not just on keypress) so
        # driving doesn't stop the instant the OpenCV window misses a repeat
        # keydown event.
        self.create_timer(0.1, lambda: self._cmd_pub.publish(self._cmd))

        cv2.namedWindow(WINDOW, cv2.WINDOW_NORMAL)
        self.get_logger().info(
            f'Loaded {len(self._rows)} row(s) from {rows_file}. Click the image '
            'window, then w/a/s/d to drive, space/k to stop, q to quit.')

    def _info_cb(self, msg):
        if self._intrinsics is None:
            self._intrinsics = (float(msg.k[0]), float(msg.k[4]), float(msg.k[2]), float(msg.k[5]))

    def _set_cmd(self, lin_x, ang_z, label):
        t = Twist()
        t.linear.x = lin_x
        t.angular.z = ang_z
        self._cmd = t
        self._last_key_label = label
        self._cmd_pub.publish(t)

    def _handle_key(self, key):
        if key == ord('w'):
            self._set_cmd(self._lin, 0.0, 'forward')
        elif key == ord('s'):
            self._set_cmd(-self._lin, 0.0, 'backward')
        elif key == ord('a'):
            self._set_cmd(self._lin * 0.6, self._ang, 'left')
        elif key == ord('d'):
            self._set_cmd(self._lin * 0.6, -self._ang, 'right')
        elif key in (ord(' '), ord('k')):
            self._set_cmd(0.0, 0.0, 'stopped')
        elif key == ord('q'):
            self.get_logger().info('Quit requested.')
            self._set_cmd(0.0, 0.0, 'stopped')
            rclpy.shutdown()

    def _synced_cb(self, odom_msg, msg):
        if self._intrinsics is None:
            return

        fx, fy, cx, cy = self._intrinsics
        pos = odom_msg.pose.pose.position
        ori = odom_msg.pose.pose.orientation
        r_wb = _quat_to_matrix(ori.x, ori.y, ori.z, ori.w)
        r_bc = _pitch_matrix(self._cam_pitch)
        r_wc = r_wb @ r_bc
        t_wb = np.array([pos.x, pos.y, pos.z])
        t_bc = np.array([self._cam_x, 0.0, self._cam_h])
        t_wc = t_wb + r_wb @ t_bc

        canvas = self._bridge.imgmsg_to_cv2(msg, desired_encoding='bgr8').copy()
        img_h, img_w = canvas.shape[:2]

        colors = [(0, 0, 255), (0, 255, 0), (255, 0, 0), (0, 255, 255),
                  (255, 0, 255), (255, 165, 0), (128, 0, 255)]

        for row_idx, points in enumerate(self._rows):
            color = colors[row_idx % len(colors)]
            pixels = []
            for p in points:
                p_w = np.array([p[0], p[1], self._ground_z])
                d_w = p_w - t_wc
                d_sensor = r_wc.T @ d_w
                x_opt, y_opt, z_opt = -d_sensor[1], -d_sensor[2], d_sensor[0]
                if z_opt <= 0.05:
                    pixels.append(None)
                    continue
                u = fx * x_opt / z_opt + cx
                v = fy * y_opt / z_opt + cy
                pixels.append((int(round(u)), int(round(v))))

            for a, b in zip(pixels, pixels[1:]):
                if a is not None and b is not None:
                    cv2.line(canvas, a, b, color, 3)
            for p in pixels:
                if p is not None and 0 <= p[0] < img_w and 0 <= p[1] < img_h:
                    cv2.circle(canvas, p, 4, color, -1)

        cv2.putText(canvas, f'cmd: {self._last_key_label}', (10, 25),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255, 255, 255), 2, cv2.LINE_AA)
        cv2.putText(canvas, 'w/a/s/d drive, space/k stop, q quit', (10, img_h - 12),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.55, (255, 255, 255), 2, cv2.LINE_AA)

        cv2.imshow(WINDOW, canvas)
        key = cv2.waitKey(1) & 0xFF
        if key != 255:
            self._handle_key(key)


def main(args=None):
    rclpy.init(args=args)
    node = LiveLabelTeleop()
    try:
        rclpy.spin(node)
    finally:
        cv2.destroyAllWindows()
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == '__main__':
    main()
